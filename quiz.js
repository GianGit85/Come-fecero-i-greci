// Le 243 combinazioni vengono "mescolate" in modo fisso: tutti i 100 risultati sono raggiungibili.
window.calcolaRisultato = risposte => {
  const indice = risposte.reduce((n, r) => n * 3 + r, 0);   // 0..242
  return ((indice * 37 + 11) % 243) % 100 + 1;
};
